const catalogs: Record<Lang, Record<string, string>> = { en, ru }

let current: Lang = 'en'

// setLanguage switches the UI language.
export function setLanguage(lang: string) {
  current = lang === 'ru' ? 'ru' : 'en'
}

// language returns the current language.
export function language(): Lang {
  return current
}

// t translates a key and returns the key itself when missing.
export function t(key: string): string {
  return catalogs[current][key] ?? catalogs.en[key] ?? key
}
